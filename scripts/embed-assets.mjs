// Embed the built frontend (dist/client) into the Worker bundle so the Worker
// can serve it under the /moho path prefix without a separate assets binding.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, extname } from "node:path";

const root = "dist/client";
const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
};

const out = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const ext = extname(p);
    if (!types[ext]) { console.warn(`skip ${p}`); continue; }
    out["/" + relative(root, p).split("\\").join("/")] = { type: types[ext], body: readFileSync(p, "utf8") };
  }
}
walk(root);
mkdirSync("worker/generated", { recursive: true });
writeFileSync(
  "worker/generated/assets.ts",
  "// Generated by scripts/embed-assets.mjs — do not edit\n" +
  "export const STATIC_ASSETS: Record<string, { type: string; body: string }> = " +
  JSON.stringify(out) + ";\n"
);
console.log(`embedded ${Object.keys(out).length} files`);
